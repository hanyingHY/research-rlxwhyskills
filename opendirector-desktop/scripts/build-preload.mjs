/**
 * Bundle the preload (bridge + guidance UI) into one CommonJS file.
 *
 * esbuild is used instead of a hand-rolled require() graph so that the preload
 * can be a sandboxed script (it may only require("electron") at runtime).
 */
import { build } from "esbuild";
import { statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const outfile = join(root, "dist", "preload.cjs");

await build({
  entryPoints: [join(root, "src", "preload", "index.js")],
  outfile,
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  external: ["electron"],
  legalComments: "none",
  charset: "utf8",
  logLevel: "warning",
  banner: {
    js: "// Generated by scripts/build-preload.mjs. Do not edit.",
  },
});

const size = statSync(outfile).size;
console.log(`preload: ${outfile} (${(size / 1024).toFixed(1)} KiB)`);
